light_color = "red"

if light_color == "red":
    print("Stop! The light is red.")
elif light_color == "yellow":
    print("You Should Wait!")
elif light_color == "green":
    print("Go! The light is green.")
else:
    print("Invalid input! Please enter a valid traffic light color.")

